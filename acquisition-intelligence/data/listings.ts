// Merge ingested (live/imported) listings on top of the seed set.
// Ingested rows win on id collision; otherwise they're appended.
// Populate data/ingested.json via `npm run ingest` (see data/inbound/README.md).
const ingestedListings = ingested as unknown as Listing[];
const byId = new Map<string, Listing>();
for (const l of SEED) byId.set(l.id, l);
for (const l of ingestedListings) byId.set(l.id, l);

export const LISTINGS: Listing[] = Array.from(byId.values());

/** Count of listings that came from the ingestion pipeline (non-seed). */
export const INGESTED_COUNT = ingestedListings.length;

export function getListing(id: string): Listing | undefined {
  return LISTINGS.find((l) => l.id === id);
}
